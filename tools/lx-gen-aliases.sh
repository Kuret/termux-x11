#!/usr/bin/env bash
# Regenerates the per-app activities that give each Linux window its own name and icon in
# Samsung DeX, in Recents and in the task switcher.
#
# Samsung labels a window's caption, taskbar entry and window list from the *activity* that
# owns the task and ignores setTaskDescription(), and it groups taskbar entries by task
# affinity. So every Linux app needs its own activity, with its own label, icon and affinity,
# or they all show up as one "Termux:X11" entry.
#
# Each app gets a generated subclass of MainActivity.MainActivityTagged (an <activity-alias>
# cannot carry its own taskAffinity, which is why these are real activities) plus a block in
# the manifest between the lx-app-activities markers.
#
# Input is a directory in the same layout /data/local/bin/lx publishes for the X11 app:
#   <id>.name   one line, the name to show   (required)
#   <id>.png    the icon                     (optional)
# so the spec can be refreshed straight off the phone:
#   adb exec-out su -c 'tar -C /data/data/com.termux.x11/files -cf - lx-tags' | tar -xf - -C <dir>
#
# Usage: tools/lx-gen-aliases.sh [spec-dir]        (default: lorie/lx-apps)

set -euo pipefail

repo=$(cd "$(dirname "$0")/.." && pwd)
spec=${1:-$repo/lorie/lx-apps}
manifest=$repo/lorie/src/main/AndroidManifest.xml
drawables=$repo/lorie/src/main/res/drawable-nodpi
java=$repo/lorie/src/main/java/com/termux/x11
begin='        <!-- lx-app-activities:begin (generated by tools/lx-gen-aliases.sh - do not edit) -->'
end='        <!-- lx-app-activities:end -->'

# Everything MainActivityTagged declares, minus taskAffinity, which each app overrides.
common='            android:theme="@style/LorieAppTheme"
            android:documentLaunchMode="intoExisting"
            android:supportsPictureInPicture="true"
            android:autoRemoveFromRecents="true"
            android:configChanges="fontScale|orientation|screenSize|keyboard|keyboardHidden|layoutDirection|locale|mcc|mnc|navigation|screenLayout|touchscreen|uiMode|smallestScreenSize|density"
            android:resizeableActivity="true"
            android:windowSoftInputMode="stateHidden|adjustNothing"
            android:exported="false" />'

[ -d "$spec" ] || { echo "no such spec directory: $spec" >&2; exit 1; }
grep -q 'lx-app-activities:begin' "$manifest" || { echo "$manifest has no lx-app-activities markers" >&2; exit 1; }

mkdir -p "$drawables"
rm -f "$drawables"/lx_app_*.png "$java"/TaggedApp_*.java

block=$(mktemp); trap 'rm -f "$block"' EXIT
printf '%s\n' "$begin" >> "$block"

shopt -s nullglob
for name in "$spec"/*.name; do
    id=$(basename "$name" .name)
    case $id in
        [a-z][a-z0-9_]*) ;;
        *) echo "skipping '$id': an id must be lowercase and start with a letter" >&2; continue ;;
    esac
    label=$(head -n1 "$name" | tr -d '\r')
    label=${label//&/&amp;}; label=${label//</&lt;}; label=${label//>/&gt;}; label=${label//\"/&quot;}
    [ -n "$label" ] || { echo "skipping '$id': empty name file" >&2; continue; }

    icon=
    if [ -f "$spec/$id.png" ]; then
        # 192px is plenty for a caption or taskbar entry and keeps the APK small.
        if command -v magick >/dev/null 2>&1; then
            magick "$spec/$id.png" -resize '192x192>' "$drawables/lx_app_$id.png"
        else
            cp "$spec/$id.png" "$drawables/lx_app_$id.png"
        fi
        icon="@drawable/lx_app_$id"
    fi

    cat > "$java/TaggedApp_$id.java" <<JAVA
package com.termux.x11;

/**
 * The window for the "$id" Linux app. Generated by tools/lx-gen-aliases.sh - do not edit.
 *
 * It exists only so the manifest can give this app its own label, icon and task affinity;
 * all behaviour comes from MainActivityTagged.
 */
public class TaggedApp_$id extends MainActivity.MainActivityTagged {
}
JAVA

    {
        printf '        <activity\n'
        printf '            android:name=".TaggedApp_%s"\n' "$id"
        printf '            android:taskAffinity="com.termux.x11.app.%s"\n' "$id"
        printf '            android:label="%s"\n' "$label"
        [ -n "$icon" ] && printf '            android:icon="%s"\n            android:roundIcon="%s"\n' "$icon" "$icon"
        printf '%s\n' "$common"
    } >> "$block"
    echo "activity com.termux.x11.TaggedApp_$id -> \"$label\"${icon:+ with icon}"
done
printf '%s\n' "$end" >> "$block"

python3 - "$manifest" "$block" <<'PY'
import re, sys
manifest, block = sys.argv[1], sys.argv[2]
text = open(manifest).read()
new = open(block).read().rstrip('\n')
pattern = re.compile(r'^[ \t]*<!-- lx-app-activities:begin.*?lx-app-activities:end -->', re.S | re.M)
text, n = pattern.subn(lambda m: new, text, count=1)
if n != 1:
    sys.exit('could not find the lx-app-activities block in ' + manifest)
open(manifest, 'w').write(text)
PY
echo "updated $manifest"
